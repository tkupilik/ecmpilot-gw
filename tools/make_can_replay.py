"""Generate a flash-resident, RX-only demo from the owner's INFO CAN capture."""
import argparse
import csv
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
IDS = {0x036, 0x0A2, 0x0B6, 0x0F6, 0x11C, 0x128, 0x1E7, 0x31A, 0x3E0}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('capture', type=Path)
    args = parser.parse_args()
    raw = args.capture.read_bytes()
    rows = list(csv.DictReader(raw.decode('utf-8-sig').splitlines()))
    origin = int(rows[0]['Time Stamp'])
    frames = []
    previous = origin
    for row in rows:
        stamp = int(row['Time Stamp'])
        if stamp < previous:
            raise ValueError('Timestamp regression: split captures explicitly')
        previous = stamp
        ident = int(row['ID'], 16)
        if ident not in IDS or row['Extended'].lower() != 'false' or row['Dir'] != 'Rx':
            continue
        length = int(row['LEN'])
        if not 0 <= length <= 8:
            raise ValueError('Not classic CAN')
        data = [int(row[f'D{i}'], 16) for i in range(1, length + 1)]
        frames.append(((stamp - origin) // 1000, ident, length, data))
    duration = (previous - origin) // 1000 + 1
    lines = ['// Generated by tools/make_can_replay.py; owner capture, not a CAN TX script.',
             f'// {args.capture.name}; SHA-256 {hashlib.sha256(raw).hexdigest()}',
             f'#define CAN_REPLAY_DURATION_MS {duration}U',
             'static const ReplayFrame frames[] = {']
    for ms, ident, length, data in frames:
        lines.append('  {%d, 0x%03X, %d, {%s}},' % (ms, ident, length, ','.join(f'0x{x:02X}' for x in data)))
    lines.append('};\n')
    (ROOT/'main/can_replay_data.inc').write_text('\n'.join(lines), encoding='utf-8')
    summary = dict(source=args.capture.name, sha256=hashlib.sha256(raw).hexdigest(),
                   source_frames=len(rows), selected_frames=len(frames), duration_ms=duration,
                   ids={f'{i:03X}':sum(f[1]==i for f in frames) for i in sorted(IDS)},
                   timing='relative microseconds floored to milliseconds; original order retained')
    (ROOT/'docs/can-replay.json').write_text(json.dumps(summary, indent=2)+'\n')
    print(json.dumps(summary, indent=2))

if __name__ == '__main__':
    main()
